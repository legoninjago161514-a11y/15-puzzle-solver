val LocalStrings = staticCompositionLocalOf { russianStrings }

object StringsProvider {
    fun resolve(language: AppLanguage, systemLang: String = Locale.getDefault().language): AppStrings {
        val code = if (language == AppLanguage.SYSTEM) systemLang.lowercase() else language.code
        return when {
            code.startsWith("ru") -> russianStrings
            code.startsWith("es") -> spanishStrings
            code.startsWith("de") -> germanStrings
            code.startsWith("fr") -> frenchStrings
            else -> englishStrings
        }
    }
}

